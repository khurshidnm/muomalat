/**
 * /xarita — Islamic finance market map. Strings under `table` are passed to a
 * client component, so they are plain strings: `{0}`, `{1}` are filled in at
 * render time (digits survive Cyrillic transliteration).
 */

function ruPlural(n: number, one: string, few: string, many: string): string {
  const d = n % 10
  const dd = n % 100
  if (d === 1 && dd !== 11) return one
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return few
  return many
}

