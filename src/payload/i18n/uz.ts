/**
 * Uzbek (Latin) admin-interface language (CMS-SPEC §6.6, PHASE0 §1.6 and
 * item 19). Payload 3.90.2 ships no `uz`, so the pack is built as the Russian
 * pack plus Uzbek overrides: a key Payload adds in a later release shows in
 * Russian until it is translated here, instead of as a raw key.
 *
 * Every one of the 587 core keys is overridden. Plural variants (`_one`,
 * `_many`, `_other`, `_none`) are kept as Russian has them; Payload picks the
 * suffix from the count, and Uzbek uses one form after a numeral ("3 ta").
 *
 * Wiring (src/payload/i18n/index.ts, used by src/payload.config.ts):
 *   i18n: {
 *     supportedLanguages: { ...uz.supportedLanguagesEntry, ru, en },
 *     fallbackLanguage: 'uz' as AcceptedLanguages,
 *     translations: { ...uz.translationsEntry, ru: { … }, en: { … } },
 *   }
 * - A fresh `{ uz: …, ru, en }` literal is an excess-property error, so the
 *   entries are spread from pre-built objects.
 * - Accept-Language never selects `uz`, but it does select `ru` or `en`, so
 *   the fallback alone is not enough: src/proxy.ts presents the `uz` language
 *   cookie on the CMS host until a staff member picks a language.
 * - `translations` needs a known language key next to `uz` (TS2559).
 * - Dates use the `ru` date-fns locale: Payload has no Uzbek one wired in, so
 *   month names and "5 минут" in "… oldin saqlandi" stay Russian.
 */

